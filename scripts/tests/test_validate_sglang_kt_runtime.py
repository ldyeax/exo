def test_worker_pool_assignment_rejects_implicit_or_invalid_layouts() -> None:
    with pytest.raises(ValueError, match="at least one NUMA"):
        validator.WorkerPoolAssignment((), ())
    with pytest.raises(ValueError, match="equal lengths"):
        validator.WorkerPoolAssignment((0, 1), (16,))
    with pytest.raises(ValueError, match="unique"):
        validator.WorkerPoolAssignment((0, 0), (8, 8))
    with pytest.raises(ValueError, match="positive"):
        validator.WorkerPoolAssignment((0,), (0,))


