def test_cuda_stream_bridge_enqueues_both_dependency_directions() -> None:
    calls: list[str] = []

    def record(name: str, result: object = None) -> object:
        calls.append(name)
        return result

    consumed, counts = validator._enqueue_cuda_stream_bridge(  # pyright: ignore[reportPrivateUsage]
        produce_cuda_input=lambda: record("cuda input producer"),
        copy_cuda_input_to_cpu=lambda: record("cuda to cpu copy"),
        submit_cpu_work=lambda: record("cpu submit"),
        sync_cpu_work=lambda: record("cpu sync"),
        copy_cpu_output_to_cuda=lambda: record("cpu to cuda copy"),
        consume_cuda_output=lambda: record("cuda output consumer", "consumed"),
    )

    assert consumed == "consumed"
    assert calls == [
        "cuda input producer",
        "cuda to cpu copy",
        "cpu submit",
        "cpu sync",
        "cpu to cuda copy",
        "cuda output consumer",
    ]
    assert counts.input_producer == 1
    assert counts.input_to_cpu_copy == 1
    assert counts.output_from_cpu_copy == 1
    assert counts.output_consumer == 1


