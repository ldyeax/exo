def test_write_receipt_is_atomic_json(tmp_path: Path) -> None:
    config = make_config()
    receipt = execute(config, FakeBackend(config))
    destination = tmp_path / "nested" / "receipt.json"

    validator.write_receipt(destination, receipt)

