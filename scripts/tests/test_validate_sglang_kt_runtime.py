class FakeBackend:
    def __init__(self, config: validator.ValidationConfig) -> None:
        self.provenance = make_provenance()
        self.packages = make_packages(self.provenance)
        self.runtime_identity = make_runtime_identity()
        self.host = make_host()
        self.cuda = make_cuda()
        self.amx = {
            (qlen, route): make_amx(config, qlen, route)
            for qlen, route in (
                (1, "direct"),
                (16, "direct"),
                (1, "cuda_stream"),
            )
        }
        self.calls: list[str] = []
        self.error_step: str | None = None

    def _raise_if_requested(self, step: str) -> None:
        if self.error_step == step:
            raise RuntimeError(f"injected {step} failure")

    def observe_provenance(
        self, config: validator.ValidationConfig
    ) -> validator.BuildProvenanceEvidence:
        assert config.gpu_uuid == GPU_UUID
        self.calls.append("provenance")
        self._raise_if_requested("provenance")
        return self.provenance

    def observe_packages(self) -> tuple[validator.PackageEvidence, ...]:
        self.calls.append("packages")
        self._raise_if_requested("packages")
        return self.packages

    def observe_runtime_identity(self) -> validator.RuntimeIdentityEvidence:
        self.calls.append("runtime_identity")
        self._raise_if_requested("runtime_identity")
        return self.runtime_identity

    def observe_host(self) -> validator.HostEvidence:
        self.calls.append("host")
        self._raise_if_requested("host")
        return self.host

    def run_cuda(
        self, config: validator.ValidationConfig
    ) -> validator.CudaExecutionEvidence:
        assert config.gpu_uuid == GPU_UUID
        self.calls.append("cuda")
        self._raise_if_requested("cuda")
        return self.cuda

    def run_amx(
        self,
        config: validator.ValidationConfig,
        qlen: int,
        route: validator.ExecutionRoute,
    ) -> validator.AmxExecutionEvidence:
        assert config.worker_pool.numa_nodes == (0,)
        step = f"amx:{qlen}:{route}"
        self.calls.append(step)
        self._raise_if_requested(step)
        return self.amx[(qlen, route)]


def execute(
    config: validator.ValidationConfig,
    backend: FakeBackend,
) -> validator.RuntimeValidationReceipt:
    return validator.execute_validation(config, backend, clock=lambda: TIMESTAMP)


def test_passes_only_complete_direct_execution_evidence() -> None:
    config = make_config()
    backend = FakeBackend(config)

    receipt = execute(config, backend)

    assert receipt.status == "passed"
    assert receipt.failures == ()
    assert receipt.capabilities == ("kt_bf16_amx_executed_v1",)
    assert receipt.profiler == "none"
    assert [item.qlen for item in receipt.amx] == [1, 16]
    assert backend.calls == [
        "provenance",
        "packages",
        "runtime_identity",
        "host",
        "cuda",
        "amx:1:direct",
        "amx:16:direct",
        "amx:1:cuda_stream",
    ]
    document = json.loads(validator.receipt_json(receipt))
    assert document["status"] == "passed"
    assert document["config"]["worker_pool"]["threads_per_subpool"] == [16]


